"""Generate the portable C# SHA-256 unrolled experiment from its canonical loop.

Development/CI-only generator; the checked-in .g.cs needs no Python at runtime.
"""
from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "workloads/challenge-sha256-v1/implementations/dotnet-portable"
SOURCE = SRC / "Sha256Kernel.cs"
GENERATED = SRC / "Sha256Kernel.Unrolled.g.cs"


def generate() -> str:
    source = SOURCE.read_text()
    assert "internal static void CompressVector(" in source
    a = source.index("    internal static ulong RunVector(int count)")
    b = source.index("    // Same 64-bit equality target", a)
    c = source.index("    internal static ulong RunVectorMatch(int count)", b)
    d = source.index("    internal static void SelfTest()", c)
    digest_driver = source[a:b]
    match_driver = source[c:d]
    assert digest_driver.count("CompressVector(block, state);") == 1
    assert match_driver.count("CompressVector(block, state);") == 1
    digest_driver = (
        digest_driver.replace("RunVector(int count)", "RunVectorOptimized(int count)")
        .replace("CompressVector(block, state);", "CompressVectorUnrolled(block, state);")
    )
    match_driver = (
        match_driver.replace("RunVectorMatch(int count)", "RunVectorMatchOptimized(int count)")
        .replace("CompressVector(block, state);", "CompressVectorUnrolled(block, state);")
    )
    lines = [
        "// Generated by tools/generate_challenge_sha256_unrolled.py; do not edit manually.",
        "// Explicit portable vectors, no architecture-specific intrinsics or unsafe code.",
        "using System.Numerics;",
        "using System.Runtime.CompilerServices;",
        "",
        "namespace Museum.ChallengeSha256;",
        "",
        "internal static partial class Sha256Kernel",
        "{",
        "    // Tier 0 is pathologically slow for this large method on .NET 10.",
        "    [MethodImpl(MethodImplOptions.AggressiveOptimization)]",
        "    internal static void CompressVectorUnrolled(",
        "        ReadOnlySpan<Vector<uint>> input, Span<Vector<uint>> digest)",
        "    {",
    ]
    for index in range(16):
        lines.append(f"        var w{index} = input[{index}];")
    for index, letter in enumerate("abcdefgh"):
        lines.append(f"        var {letter} = VectorHotState[{index}];")
    for i in range(10, 64):
        j = i & 15
        lines.append("        {")
        if i >= 16:
            lines.append(
                f"            w{j} = w{j} + S0(w{(i-15)&15})"
                f" + w{(i-7)&15} + S1(w{(i-2)&15});"
            )
        lines += [
            f"            var t1 = h + B1(e) + ((e & f) ^ (~e & g)) + VectorRound[{i}] + w{j};",
            "            var t2 = B0(a) + ((a & b) ^ (a & c) ^ (b & c));",
            "            h = g; g = f; f = e; e = d + t1;",
            "            d = c; c = b; b = a; a = t1 + t2;",
            "        }",
        ]
    for index, letter in enumerate("abcdefgh"):
        lines.append(f"        digest[{index}] = VectorInitial[{index}] + {letter};")
    lines.append("    }")
    lines.append("")
    return "\n".join(lines) + "\n" + digest_driver + match_driver + "}\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    opts = parser.parse_args()
    text = generate()
    if opts.check:
        if not GENERATED.is_file() or GENERATED.read_text() != text:
            raise SystemExit("generated SHA-256 C# source is stale; regenerate")
        print("Generated C# in sync")
    else:
        GENERATED.write_text(text)
        print(f"Wrote {GENERATED.relative_to(ROOT)}")
